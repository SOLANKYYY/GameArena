// Mines multiplier table - approximation of Stake's table
// multiplier = floors of (0.99 * (25! / ((25-mines)!)) / ((25-revealed)! / ((25-mines-revealed)!)))
export function calculateMinesMultiplier(numMines: number, numRevealed: number): number {
  if (numRevealed === 0) return 1.0;
  const safeTiles = 25 - numMines;
  let multiplier = 1;
  for (let i = 0; i < numRevealed; i++) {
    multiplier *= (25 - i) / (safeTiles - i);
  }
  multiplier *= 0.99; // 1% house edge
  return Math.floor(multiplier * 100) / 100;
}
